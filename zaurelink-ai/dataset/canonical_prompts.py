PROMPTS = {
    ("market", "en"): MARKET_EN,
    ("market", "ha"): MARKET_HA,
    ("campus", "en"): CAMPUS_EN,
    ("campus", "ha"): CAMPUS_HA,
}
def get_prompt(environment: str, app_user_language: str) -> str:
    """Return the canonical system prompt for a given configuration.
    Raises KeyError if the combination is invalid.
    """
    key = (environment, app_user_language)
    if key not in PROMPTS:
        raise KeyError(
            f"No canonical prompt for environment={environment!r}, "
            f"app_user_language={app_user_language!r}. "
            f"Valid combinations: {sorted(PROMPTS.keys())}"
        )
    return PROMPTS[key]
